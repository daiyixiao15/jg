const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {game}=require('./game.test.cjs');
let plays=0;const effects={currentTime:9,play(){plays++;return Promise.resolve();}};
const context={document:{hidden:false,addEventListener(){}},localStorage:{getItem(){return null},setItem(){}}};
vm.createContext(context);vm.runInContext(fs.readFileSync('src/cover-audio.js','utf8'),context);
const audio=context.GameCoverAudio.create({effectsAudio:effects});
audio.click();assert.equal(plays,1);assert.equal(effects.currentTime,0);assert.equal(effects.volume,.7);
audio.setEffectsVolume(0);audio.click();assert.equal(plays,1);
audio.setEffectsVolume(.3);audio.click();assert.equal(effects.volume,.3);assert.equal(plays,2);
context.document.hidden=true;audio.click();assert.equal(plays,2);
let clicks=0;const g=game({}, {update(){},click(){clicks++;}});
g.next();assert.equal(clicks,0);g.act('start');assert.equal(clicks,1);
g.act('begin-adventure');assert.equal(clicks,2);g.next();g.act('advance');assert.equal(clicks,2);
g.finishText();g.act('settings');assert.equal(clicks,3);g.act('close');assert.equal(clicks,3);
g.next();assert.equal(clicks,3);
g.act('item','apple');assert.equal(clicks,3);g.act('close');assert.equal(clicks,3);
g.act('inspect','shampoo');assert.equal(clicks,3);g.act('close');assert.equal(clicks,3);
g.act('gift-inspect','lipstick');assert.equal(clicks,3);
assert.ok(fs.statSync('assets/button-click.mp3').size>0);
console.log('PASS: button-only click sound, silent blank clicks/story advancement, effects volume and hidden-page silence.');
